"""Phase 0 inventory of report/final_report/fpr-8.tex -> report/final_report/fixes/inventory.md"""
import re
from pathlib import Path

R = Path(__file__).resolve().parents[2] / "report/final_report"
tex = (R / "fpr-8.tex").read_text(encoding="utf-8")
for m in re.finditer(r"\\input\{(sections/[^}]+)\}", tex):
    tex = tex.replace(m.group(0), (R / (m.group(1) + ".tex")).read_text(encoding="utf-8"))
aux = (R / "fpr-8.aux").read_text(encoding="utf-8")
num = {m.group(1): (m.group(2), m.group(3)) for m in re.finditer(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}\{(\d+)\}", aux)}
out = ["# Inventory of fpr-8.tex (generated by tools/report_stats/inventory.py)\n", "## Sections\n"]
app = tex.index("\\appendix") if "\\appendix" in tex else len(tex)
for m in re.finditer(r"\\(section|subsection|subsubsection)\{(.+?)\}\s*\n\\label\{([^}]+)\}", tex):
    n, pg = num.get(m.group(3), ("?", "?"))
    part = "APPENDIX (mid-term)" if m.start() > app else ("final" if "Final" in m.group(2) or m.start() > tex.index("Final Phase I") else "mid-term/intro")
    out.append(f"- {'  ' * (m.group(1).count('sub'))}{n} {m.group(2)} (`{m.group(3)}`, p.{pg}) [{part}]")
out.append("\n## Figures and tables (number, label, page, caption start)\n")
for m in re.finditer(r"\\caption\{(.*?)\}\s*\n?\\label\{((?:fig|tab):[^}]+)\}", tex, re.S):
    n, pg = num.get(m.group(2), ("?", "?"))
    cap = re.sub(r"\s+", " ", m.group(1))
    src = re.search(r"Source:[^.;}]*", cap)
    out.append(f"- {m.group(2).split(':')[0]} {n} `{m.group(2)}` p.{pg}: {cap[:110]}... | source tag: {src.group(0) if src else 'NONE'}")
out.append("\n## Numbers quoted for speed, delay, F1 and resources (line: excerpt)\n")
pat = re.compile(r"(\d+(\.\d+)?--?\d*(\.\d+)?\$?\\times|real time|\d+\.\d\\,?s\b|delay|F1 \$?\d|\d+(\.\d)?\\%|LUT|BRAM|DSP)")
for i, line in enumerate((R / "fpr-8.tex").read_text(encoding="utf-8").splitlines(), 1):
    if pat.search(line) and not line.lstrip().startswith("%"):
        out.append(f"- L{i}: {line.strip()[:160]}")
(R / "fixes").mkdir(exist_ok=True)
(R / "fixes/inventory.md").write_text("\n".join(out), encoding="utf-8")
print(len(out), "lines")
